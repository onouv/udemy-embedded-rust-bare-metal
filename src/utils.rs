pub mod bits {
    // clearing bits
    // value    ???? ???? ???? ???? ???? ??xy ???? ????
    // mask     0000 0000 0000 0000 0000 0011 0000 0000
    // !mask    1111 1111 1111 1111 1111 1100 1111 1111
    // nval     ???? ???? ???? ???? ???? ??00 ???? ????
    pub fn clear(value: u32, mask: u32) -> u32 {
        value & !mask
    }

    // setting bits
    // value    ???? ???? ???? ???? ???? ??xy ???? ????
    // mask     0000 0000 0000 0000 0000 0011 0000 0000
    // nval     0000 0000 0000 0000 0000 00xy 0000 0000
    pub fn set(value: u32, mask: u32) -> u32 {
        value | mask
    }

    // setting bits at offset
    // value        ???? ???? ???? ???? ???? ??xy ???? ????
    // mask         0000 0000 0000 0000 0000 0011 0000 0000
    // value & mask 0000 0000 0000 0000 0000 00xy 0000 0000
    // result       0000 0000 0000 0000 0000 0000 0000 00xy
    pub fn get(value: u32, mask: u32, offset: u32) -> Result<u32, ()> {
        if offset > 15 {
            return Err(());
        }

        Ok((value & mask) >> offset)
    }
}
